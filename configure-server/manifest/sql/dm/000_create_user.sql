CREATE TABLESPACE CONFIG_CENTER_DATA
    DATAFILE 'CONFIG_CENTER_DATA.DBF' SIZE 128 AUTOEXTEND ON NEXT 32 MAXSIZE 32767;

CREATE USER CONFIG_CENTER IDENTIFIED BY "ConfigCenter_123"
    DEFAULT TABLESPACE CONFIG_CENTER_DATA;

GRANT RESOURCE, PUBLIC, VTI, SOI TO CONFIG_CENTER;
GRANT CREATE TABLE, CREATE VIEW, CREATE INDEX, CREATE SEQUENCE TO CONFIG_CENTER;
