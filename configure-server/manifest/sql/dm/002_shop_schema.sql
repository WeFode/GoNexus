
CREATE TABLE "CONFIG_CENTER"."PRODUCTS"
(
    "ID" BIGINT IDENTITY(1, 1) NOT NULL,
    "NAME" VARCHAR(128) NOT NULL,
    "DESCRIPTION" CLOB,
    "PRICE" DECIMAL(12,2) DEFAULT 0 NOT NULL,
    "STOCK" INT DEFAULT 0 NOT NULL,
    "STATUS" SMALLINT DEFAULT 1 NOT NULL,
    "CREATED_AT" TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UPDATED_AT" TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT "PK_PRODUCTS" PRIMARY KEY("ID")
) TABLESPACE "CONFIG_CENTER_DATA";

COMMENT ON TABLE "CONFIG_CENTER"."PRODUCTS" IS '商品表（脚手架示例）';
COMMENT ON COLUMN "CONFIG_CENTER"."PRODUCTS"."NAME" IS '商品名称';
COMMENT ON COLUMN "CONFIG_CENTER"."PRODUCTS"."DESCRIPTION" IS '商品描述';
COMMENT ON COLUMN "CONFIG_CENTER"."PRODUCTS"."PRICE" IS '价格';
COMMENT ON COLUMN "CONFIG_CENTER"."PRODUCTS"."STOCK" IS '库存';
COMMENT ON COLUMN "CONFIG_CENTER"."PRODUCTS"."STATUS" IS '状态：1上架 0下架';

CREATE OR REPLACE INDEX "CONFIG_CENTER"."IDX_PRODUCTS_NAME" ON "CONFIG_CENTER"."PRODUCTS"("NAME" ASC) TABLESPACE "CONFIG_CENTER_DATA";
CREATE OR REPLACE INDEX "CONFIG_CENTER"."IDX_PRODUCTS_STATUS" ON "CONFIG_CENTER"."PRODUCTS"("STATUS" ASC) TABLESPACE "CONFIG_CENTER_DATA";



