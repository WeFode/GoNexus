-- 配置中心审计库 + 发布编排表（达梦 DM8）
-- 表名、列名使用双引号全大写，便于统一管理
-- 要求 DM8.1+（支持 CREATE TABLE IF NOT EXISTS）

-- ==================== config_history ====================
CREATE TABLE IF NOT EXISTS "CONFIG_HISTORY" (
    "ID"          BIGINT IDENTITY(1,1) NOT NULL,
    "CONFIG_KEY"  VARCHAR(255) NOT NULL,
    "VERSION"     INT NOT NULL,
    "CONTENT"     CLOB,
    "ACTION_TYPE" VARCHAR(16) NOT NULL,
    "OPERATOR"    VARCHAR(64) DEFAULT '',
    "REMARK"      VARCHAR(255) DEFAULT '',
    "CREATED_AT"  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT "PK_CONFIG_HISTORY" PRIMARY KEY ("ID")
    );

CREATE INDEX "IDX_CONFIG_HISTORY_KEY_VER" ON "CONFIG_HISTORY" ("CONFIG_KEY", "VERSION" DESC);
CREATE UNIQUE INDEX "UK_CONFIG_HISTORY_KEY_VER" ON "CONFIG_HISTORY" ("CONFIG_KEY", "VERSION");

COMMENT ON TABLE "CONFIG_HISTORY" IS '配置发布审计（etcd 写入成功后追加；回滚读此表）';
COMMENT ON COLUMN "CONFIG_HISTORY"."CONFIG_KEY" IS 'etcd 全路径，如 /config-center/services/shop-server';
COMMENT ON COLUMN "CONFIG_HISTORY"."ACTION_TYPE" IS 'CREATE / UPDATE / BASELINE（变更前快照） / DELETE / ROLLBACK';

-- ==================== deploy_nodes ====================
CREATE TABLE IF NOT EXISTS "DEPLOY_NODES" (
    "NODE_ID"          VARCHAR(64) NOT NULL,
    "HOSTNAME"         VARCHAR(255) DEFAULT '',
    "OS"               VARCHAR(32) DEFAULT '',
    "ARCH"             VARCHAR(32) DEFAULT '',
    "DOCKER_PLATFORM"  VARCHAR(64) DEFAULT '',
    "DOCKER_NETWORK"   VARCHAR(128) DEFAULT '',
    "LOOPBACK_AS"      VARCHAR(128) DEFAULT '',
    "NCPU"              INT DEFAULT 0,
    "MEMORY_BYTES"      BIGINT DEFAULT 0,
    "CPU_USED_PERCENT"  DOUBLE DEFAULT -1,
    "MEMORY_USED_BYTES" BIGINT DEFAULT -1,
    "MEMORY_SOURCE"     VARCHAR(16) DEFAULT '',
    "HOST_PORTS"        CLOB,
    "AGENT_VERSION"     VARCHAR(32) DEFAULT '',
    "CONTAINERS"       CLOB,
    "LAST_SEEN"        TIMESTAMP,
    CONSTRAINT "PK_DEPLOY_NODES" PRIMARY KEY ("NODE_ID")
    );

COMMENT ON TABLE "DEPLOY_NODES" IS 'deploy-agent 心跳；last_seen 用于在线判定';

-- ==================== deploy_artifacts ====================
CREATE TABLE IF NOT EXISTS "DEPLOY_ARTIFACTS" (
    "ID"              BIGINT IDENTITY(1,1) NOT NULL,
    "SERVICE_NAME"    VARCHAR(128) NOT NULL,
    "IMAGE_NAME"      VARCHAR(255) NOT NULL,
    "PLATFORM"        VARCHAR(64) NOT NULL,
    "CONTAINER_PORT"  INT DEFAULT 0,
    "FILE_PATH"       VARCHAR(512) NOT NULL,
    "FILE_SIZE"       BIGINT DEFAULT 0,
    "SHA256"          VARCHAR(64) DEFAULT '',
    "OPERATOR"        VARCHAR(64) DEFAULT '',
    "CREATED_AT"      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT "PK_DEPLOY_ARTIFACTS" PRIMARY KEY ("ID")
    );

COMMENT ON TABLE "DEPLOY_ARTIFACTS" IS '上传的 docker save tar 元数据';

-- ==================== deploy_jobs ====================
CREATE TABLE IF NOT EXISTS "DEPLOY_JOBS" (
    "ID"              BIGINT IDENTITY(1,1) NOT NULL,
    "NODE_ID"         VARCHAR(64) NOT NULL,
    "ARTIFACT_ID"     BIGINT DEFAULT 0,
    "SERVICE_NAME"    VARCHAR(128) NOT NULL,
    "ACTION"          VARCHAR(16) NOT NULL,
    "STATUS"          VARCHAR(16) NOT NULL,
    "IMAGE_NAME"      VARCHAR(255) DEFAULT '',
    "HOST_PORT"       INT DEFAULT 0,
    "DOCKER_NETWORK"  VARCHAR(128) DEFAULT '',
    "LOOPBACK_AS"     VARCHAR(128) DEFAULT '',
    "MESSAGE"         CLOB,
    "OPERATOR"        VARCHAR(64) DEFAULT '',
    "CREATED_AT"      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UPDATED_AT"      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT "PK_DEPLOY_JOBS" PRIMARY KEY ("ID")
    );

CREATE INDEX "IDX_DEPLOY_JOBS_NODE" ON "DEPLOY_JOBS" ("NODE_ID", "STATUS", "ID");

COMMENT ON TABLE "DEPLOY_JOBS" IS '发布任务：waiting（灰度等待）/ pending → running → success/failed；action=deploy|rollback|canary|start|stop|restart|stop-canary';